# Check if DLC environment variable is set
if (-not $env:DLC) {
  Write-Error "DLC environment variable is not set. Please set it to your OpenEdge installation directory."
  exit 1
}

if ($args.Count -lt 1) {
  Write-Error "Usage: compilexref.ps1 <FirstParam> [args for mbpro...]"
  exit 2
}

$first = $args[0]
$rest  = if ($args.Count -gt 1) { $args[1..($args.Count-1)] } else { @() }

# --- Input validation (all arguments are untrusted: user input or openedge-project.json values) ---

# Source file: must exist, must be an ABL source extension, must not contain shell metacharacters.
if (-not (Test-Path $first -PathType Leaf)) {
  Write-Error "Source file not found: $first"
  exit 2
}
$allowedExtensions = @('.p', '.w', '.i', '.cls')
$ext = [System.IO.Path]::GetExtension($first).ToLowerInvariant()
if ($allowedExtensions -notcontains $ext) {
  Write-Error "Source file must be one of: $($allowedExtensions -join ', '). Got: $first"
  exit 2
}

# Reject cmd.exe metacharacters in every argument. The final command is executed via cmd.exe /c,
# so & | < > ^ % " and backtick in any token would allow command injection or env-var expansion.
$cmdMetaPattern = '[&|<>^%"`]'
if ($first -match $cmdMetaPattern) {
  Write-Error "Source file path contains characters that are not allowed in a command line: $first"
  exit 2
}
foreach ($token in $rest) {
  if ($token -match $cmdMetaPattern) {
    Write-Error "Startup parameter contains characters that are not allowed in a command line: $token"
    exit 2
  }
}

# Check for existing xref file generated by OpenEdge ABL extension
$projectJsonPath = "openedge-project.json"
if (Test-Path $projectJsonPath) {
  try {
    $projectJson = Get-Content $projectJsonPath -Raw | ConvertFrom-Json

    # Find the build directory from buildPath
    $buildDir = $null
    foreach ($entry in $projectJson.buildPath) {
      if ($entry.type -eq "source" -and $entry.PSObject.Properties.Name -contains "build") {
        $buildDir = $entry.build
        break
      }
    }

    if ($buildDir) {
      # Get the source file path relative to workspace
      $sourceFile = $first

      # Remove the source directory prefix (e.g., "src\") to get relative path
      $relativePath = $sourceFile
      if ($projectJson.buildPath) {
        foreach ($entry in $projectJson.buildPath) {
          if ($entry.type -eq "source") {
            $srcPath = $entry.path
            if ($sourceFile.StartsWith($srcPath + "\") -or $sourceFile.StartsWith($srcPath + "/")) {
              $relativePath = $sourceFile.Substring($srcPath.Length + 1)
              break
            }
          }
        }
      }

      # Append .xref to the full filename
      $xrefFileName = [System.IO.Path]::GetFileName($relativePath) + ".xref"
      $xrefSubDir = [System.IO.Path]::GetDirectoryName($relativePath)

      # Construct the .pct path: <build>\.pct\<relative-path>\<filename>.xref
      $pctXrefPath = Join-Path $buildDir ".pct"
      if ($xrefSubDir) {
        $pctXrefPath = Join-Path $pctXrefPath $xrefSubDir
      }
      $pctXrefPath = Join-Path $pctXrefPath $xrefFileName

      # Check if the .pct xref file exists and is newer than source
      if (Test-Path $pctXrefPath) {
        $sourceTime = (Get-Item $sourceFile).LastWriteTime
        $xrefTime = (Get-Item $pctXrefPath).LastWriteTime

        if ($xrefTime -ge $sourceTime) {
          Write-Host "Found up-to-date xref file generated by OpenEdge ABL extension:"
          Write-Host $pctXrefPath

          # Open in an editor when one is available; otherwise just report the path
          if (Get-Command code -ErrorAction SilentlyContinue) {
            Write-Host "Opening in editor..."
            code $pctXrefPath
          } elseif (Get-Command devin -ErrorAction SilentlyContinue) {
            Write-Host "Opening in editor..."
            devin $pctXrefPath
          }
          exit 0
        }
        else {
          Write-Host "Found xref file but it's older than source. Recompiling..."
        }
      }
    }
  }
  catch {
    # If parsing fails, just continue with compilation
    Write-Host "Could not parse openedge-project.json or locate existing xref. Proceeding with compilation..."
  }
}

# Build a raw tail string EXACTLY as tokens joined by spaces
# (this preserves order; and since you used --%, tokens are already literal)
$restLine = $rest -join ' '

# Get the directory where this script is located
$scriptPath = Join-Path $PSScriptRoot "compilexref.p"

# Build a single command line for cmd.exe to execute
$cmdLine = $env:DLC + "\bin\_progres -b -p ""$scriptPath"" $restLine -param $first"

# Display the full command for verification BEFORE execution (mandatory review step)
Write-Host '==== COMMAND LINE TO EXECUTE (via cmd.exe) ===='
Write-Host $cmdLine
Write-Host '================================================'

# Execute via cmd so mbpro.bat sees one cohesive command line
cmd.exe /s /c $cmdLine
